def get_provider_by_id(provider_id: str) -> Optional[DataSourceProvider]:
    """Retrieve provider metadata by ID."""
    return MASTER_DATA_PROVIDERS.get(provider_id)

def get_all_providers() -> List[DataSourceProvider]:
    """Return all registered data providers sorted by authority tier and name."""
    return list(MASTER_DATA_PROVIDERS.values())

def search_providers(
    query: Optional[str] = None,
    category: Optional[str] = None,
    protocol: Optional[str] = None,
    authority_tier: Optional[str] = None
) -> List[DataSourceProvider]:
    """Filter providers by text search, category, protocol, or authority tier."""
    results = list(MASTER_DATA_PROVIDERS.values())
    
    if query:
        q = query.strip().lower()
        filtered = []
        for p in results:
            match = (
                q in p.name.lower() or
                q in p.official_name.lower() or
                q in p.organization.lower() or
                q in p.category.value.lower() or
                any(q in sub.lower() for sub in p.subcategories) or
                any(q in var.lower() for var in p.variables) or
                any(q in prod.lower() for prod in p.example_products)
            )
            # Special keyword aliases requested in user prompt
            if q == "dem" and ("TERRAIN" in p.subcategories or p.category == ProviderCategory.TERRAIN):
                match = True
            elif q == "rainfall" and ("RAINFALL" in p.subcategories or p.category == ProviderCategory.RAINFALL):
                match = True
            elif q == "flood" and ("FLOOD" in p.subcategories or p.category == ProviderCategory.FLOOD):
                match = True
            elif q == "dam" and ("HYDROLOGY" in p.subcategories or "dam" in p.name.lower() or "cwc" in p.id or "nrld" in p.id or "wris" in p.id):
                match = True
            elif q == "river" and ("HYDROLOGY" in p.subcategories or "river" in p.name.lower()):
                match = True
            elif q == "population" and ("POPULATION" in p.subcategories or p.category == ProviderCategory.POPULATION):
                match = True
            elif q == "satellite" and ("SATELLITE" in p.subcategories or p.category == ProviderCategory.SATELLITE):
                match = True
            elif q == "hydrology" and ("HYDROLOGY" in p.subcategories or p.category == ProviderCategory.HYDROLOGY):
                match = True
            elif q == "buildings" and ("BUILDINGS" in p.subcategories or p.category == ProviderCategory.BUILDINGS):
                match = True
            elif q == "roads" and ("INFRASTRUCTURE" in p.subcategories or "road" in p.name.lower() or "morth" in p.organization.lower()):
                match = True
            
            if match:
                filtered.append(p)
        results = filtered

    if category and category.upper() != "ALL":
        cat_upper = category.upper()
        results = [
            p for p in results 
            if p.category.value == cat_upper or cat_upper in [s.upper() for s in p.subcategories]
        ]

    if protocol and protocol.upper() != "ALL":
        proto = protocol.upper()
        if proto == "STAC":
            results = [p for p in results if p.stac_available]
        elif proto in ["WMS", "WFS", "WMTS", "WCS", "OGC"]:
            results = [p for p in results if p.wms_available or p.wfs_available or p.wmts_available or p.api_type == "OGC_API"]
        elif proto == "REST":
            results = [p for p in results if p.rest_available or p.api_type == "REST"]
        elif proto == "DOWNLOAD":
            results = [p for p in results if p.download_available]

    if authority_tier and authority_tier.upper() != "ALL":
        results = [p for p in results if p.authority_tier.value.upper() == authority_tier.upper()]

    return results
